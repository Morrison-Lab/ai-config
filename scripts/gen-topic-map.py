#!/usr/bin/env python3
"""Generate docs/topic-map.md: one row per skill and shared fragment (ai-config#949).

Retrieval failed three times in one session on material already in context,
because grep answers "where does this string occur" while the question was
"what covers this concept". A hand-written map goes stale on the next addition
with nothing to notice, so this script derives the map from what each file
already carries and `--check` fails when the committed map differs.

Sources:
  skills/<name>/SKILL.md   frontmatter `description:` (and optional `keywords:`)
  shared/**/*.md           first paragraph (and optional frontmatter `keywords:`);
                           `*.rationale.md` and `*.cases.md` are companions of a
                           fragment, not fragments, and are skipped.

`keywords:` is where search terms accumulate. When a search misses something
that turns out to be present, append the term searched for to that file's
`keywords:` so the next search finds it. Run without arguments to regenerate.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = Path("docs") / "topic-map.md"
COMPANION = re.compile(r"\.(rationale|cases)\.md$")
LINK = re.compile(r"\[([^\]]*)\]\([^)]*\)")
FRONT = re.compile(r"\A---\n(.*?)\n---\n", re.S)


def frontmatter(text: str) -> tuple[dict[str, str], str]:
    m = FRONT.match(text)
    if not m:
        return {}, text
    fields: dict[str, str] = {}
    for line in m.group(1).splitlines():
        k, sep, v = line.partition(":")
        if sep and not line.startswith((" ", "-")):
            fields[k.strip()] = v.strip().strip("\"'")
    return fields, text[m.end():]


def first_paragraph(body: str) -> str:
    for block in re.split(r"\n\s*\n", body.strip()):
        block = block.strip()
        if block and not block.startswith(("#", "<!--", "|", "```")):
            # Links are relative to the source file, so they break here: keep the text.
            return " ".join(LINK.sub(r"\1", block).split())
    return ""


def clip(s: str, n: int = 160) -> str:
    s = s.replace("|", "\\|").replace(chr(0x2014), " --- ").replace(chr(0x2192), "->")
    return s if len(s) <= n else s[: n - 3].rstrip() + "..."


def submodule_paths(root: Path) -> list[str]:
    """Paths of git submodules: their files exist in some checkouts and not in others."""
    gm = root / ".gitmodules"
    if not gm.is_file():
        return []
    return re.findall(r"^\s*path\s*=\s*(\S+)", gm.read_text(encoding="utf-8"), re.M)


def rows(root: Path) -> list[tuple[str, str, str, str]]:
    out = []
    subs = submodule_paths(root)
    for p in sorted((root / "skills").glob("*/SKILL.md")):
        fm, body = frontmatter(p.read_text(encoding="utf-8"))
        desc = fm.get("description") or first_paragraph(body)
        out.append(("skill", p.parent.name, desc, fm.get("keywords", "")))
    for p in sorted((root / "shared").rglob("*.md")):
        rel = p.relative_to(root / "shared")
        in_submodule = any(("shared/" + rel.as_posix()).startswith(s + "/") for s in subs)
        if COMPANION.search(p.name) or rel.parts[0] == "vendored" or in_submodule:
            continue
        fm, body = frontmatter(p.read_text(encoding="utf-8"))
        out.append(("shared", rel.as_posix(), first_paragraph(body), fm.get("keywords", "")))
    return out


def render(root: Path) -> str:
    lines = [
        "# Topic map",
        "",
        "<!-- Generated by scripts/gen-topic-map.py; do not edit by hand. -->",
        "",
        "One row per skill and shared fragment, taken from its own description.",
        "Add a `keywords:` frontmatter field to a file to make it findable by a term",
        "its description does not use (ai-config#949).",
        "",
    ]
    for kind, title, path in (("skill", "Skills", "skills/{}/SKILL.md"),
                              ("shared", "Shared fragments", "shared/{}")):
        lines += [f"## {title}", "", "| File | Covers | Keywords |", "| --- | --- | --- |"]
        for k, name, desc, kw in rows(root):
            if k == kind:
                lines.append(f"| `{path.format(name)}` | {clip(desc)} | {clip(kw)} |")
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if the committed map is stale")
    ap.add_argument("--root", type=Path, default=ROOT)
    args = ap.parse_args(argv)
    text = render(args.root)
    target = args.root / OUT
    if args.check:
        if not target.is_file() or target.read_text(encoding="utf-8") != text:
            print(f"{OUT} is stale; run python3 scripts/gen-topic-map.py", file=sys.stderr)
            return 1
        return 0
    target.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
